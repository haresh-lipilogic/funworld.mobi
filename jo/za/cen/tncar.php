ج. الخدمة متوافقة مع Android و iOS (للأجهزة المحمولة). أنت تدرك أن المكتبة الكاملة للألعاب المحمولة المقدمة من خلال الخدمة قد لا تكون متاحة على جميع الأجهزة وأنظمة التشغيل. على سبيل المثال: قد تكون بعض الألعاب متاحة فقط على أجهزة Android وليس على أجهزة iOS. قد تعتمد قدرتك على الوصول إلى الألعاب وتشغيلها ، من بين أشياء أخرى ، على جهازك ونظام التشغيل وسعة الشبكة وظروفها. من جانبها ، تحتفظ الشركة بالحق في تغيير المحتوى وخياراته (بما في ذلك الأهلية لميزات معينة) دون إشعار مسبق.<br><br>

