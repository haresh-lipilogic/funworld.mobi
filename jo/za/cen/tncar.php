<b>10. المحتوى</b>
<br><br>
أ. جميع النصوص والرسومات والألعاب وواجهات المستخدم والواجهات المرئية والصور والعلامات التجارية والشعارات والأصوات والموسيقى والأعمال الفنية ورموز الكمبيوتر (يُشار إليها مجتمعة باسم "المحتوى") ، بما في ذلك ، على سبيل المثال لا الحصر ، التصميم والهيكل والاختيار والتنسيق ، التعبير أو "شكل ومحتوى هذا المحتوى" ، مضمنًا أو معروضًا بطريقة أو بأخرى على الخدمات أو عليها ، مملوكة أو خاضعة لرقابة أو مرخصة من قبل الشركة ومحمية بموجب الحقوق التجارية وحقوق التأليف والنشر وقوانين براءات الاختراع. العلامات التجارية وحقوق الملكية الفكرية المختلفة وقوانين المنافسة غير المشروعة.
<br><br>
ب. باستثناء ما هو منصوص عليه صراحةً في شروط الخدمة هذه ، لا يجوز نسخ أي جزء من الخدمات أو المحتوى أو إعادة إنتاجه أو إعادة نشره أو تحميله أو نشره أو عرضه علنًا أو ترميزه أو ترجمته أو نقله أو توزيعه بأي طريقة (بما في ذلك "النسخ المتطابق") إلى أي جهاز كمبيوتر أو خادم أو موقع ويب أو أي وسيلة أخرى للنشر أو التوزيع أو لأي غرض تجاري آخر دون موافقة كتابية صريحة مسبقة منا. من الشركة.
<br><br>
ج. يجوز لك استخدام معلومات حول خدمات ومنتجات وخدمات الشركة (مثل: أوراق البيانات ومقالات قاعدة المعارف والمواد المماثلة) التي تقدمها الشركة لأغراض التنزيل ، شريطة (1) عدم إزالة أي لغة إشعار ملكية ، (2) أنك تستخدم هذه المعلومات فقط لأغراض معلوماتك الشخصية غير التجارية ولا تنسخ هذه المعلومات أو تنشرها على أي جهاز كمبيوتر متصل بالشبكة أو تبثها في أي وسائط ، (3) أنك لا تقوم بعمل أي منها تعديلات على هذه المعلومات ، (4) أنك لا تقدم أي تعهدات أو ضمانات إضافية تتعلق بهذه الوثائق.
<br><br>
<b>11. إخلاء المسؤولية ، لا ضمانات</b>
<br><br>
يتم توفير الخدمات كما هي وتخضع للتوافر. تخلي الشركة ومساهموها والشركات التابعة والتابعة لها والمسؤولون والمديرون والموظفون والمقاولون والوكلاء والممثلون وشركاء الأعمال والبائعون والعملاء والمرخصون والمستشارون ("كيانات الشركة") مسؤوليتهم صراحةً عن أي ضمانات وشروط من أي نوع ، سواء صريحة أو ضمنية ، بما في ذلك الضمانات أو الشروط الخاصة بالتسويق أو الملاءمة لغرض معين أو سند الملكية أو التمتع الهادئ أو الدقة أو عدم الانتهاك. من بين أشياء أخرى ، لا تقدم كيانات الشركة أي ضمانات على أن: (أ) الخدمات سوف تلبي متطلباتك ؛ (ب) ستكون الخدمات متاحة على أساس مستمر وفي الوقت المناسب أو بدون أخطاء ؛ أو (ج) المعلومات التي يمكن الحصول عليها من الخدمات دقيقة أو موثوقة.
<br><br>
الشركة ليست مسؤولة عن استخدام أي مستخدم للخدمات. الشركة ليست مسؤولة عن أي خطأ غير مقصود أو حذف أو توقف أو حذف أو عيب أو تأخير في التشغيل أو النقل أو فشل خط الاتصال أو السرقة أو التدمير أو الوصول غير المصرح به أو تغيير أي اتصال مع مستخدمين آخرين. لا تتحمل الشركة أي مسؤولية من أي نوع عن عدم توفر الخدمات أو عن أي فقدان للبيانات أو المعاملات الناتجة عن الانقطاعات المخطط لها أو غير المخطط لها في النظام ، أو التأخيرات الناتجة ، أو سوء التسليم أو عدم تسليم المعلومات الناتجة عن انقطاع النظام. لا تتحمل الشركة تحت أي ظرف من الظروف مسؤولية أي خسارة أو ضرر ، بما في ذلك الأضرار التي تلحق بالممتلكات أو الإصابة الشخصية أو الوفاة الناتجة عن استخدام الخدمات أو أي شيء يتم تنزيله أو استلامه من الخدمات. لا يوجد في شروط الخدمة هذه ما يؤثر على الحقوق القانونية لأي مستهلك أو يستثني أو يقيد أي مسؤولية ناتجة عن الإهمال الجسيم أو سوء السلوك المتعمد للشركة أو بسبب الوفاة أو الإصابة الشخصية الناتجة عن أي إهمال أو احتيال في الشركة.
<br><br>
<b>12. تحديد المسؤولية</b>
<br><br>
لا تتحمل الشركة بأي حال من الأحوال المسؤولية تجاهك أو تجاه أي طرف ثالث عن خسارة أي أرباح أو أي أضرار غير مباشرة أو تبعية أو عرضية أو خاصة أو عقابية تنشأ عن أو استخدامك للخدمات ، حتى لو تم إبلاغ كيانات الشركة من احتمال حدوث مثل هذه الأضرار. بصرف النظر عن أي شيء آخر منصوص عليه في هذه الوثيقة ، فإن مسؤولية كيانات الشركة تجاهك عن أي أضرار تنشأ عن أو تتعلق بالخدمات أو استخدامك للخدمات (لأي سبب من الأسباب وبغض النظر عن شكل الإجراء) ، ستكون في جميع الأوقات يقتصر على المبالغ التي دفعتها للشركة مقابل الخدمات ، إن وجدت. من جهتك ، أنت تقر وتوافق على أنه إذا لم تدفع أي رسوم اشتراك للخدمة خلال هذه الفترة الزمنية ، فإن العلاج الوحيد لأي نزاع هو التوقف عن استخدام الخدمة وإلغاء حسابك / اشتراكك. ينعكس تحديد المسؤولية هذا في منفعة أي خلفاء لكيانات الشركة ، وفي كل حالة ، تكون المسؤولية محدودة إلى أقصى حد يسمح به القانون. لا تسمح بعض الولايات القضائية بتحديد أو استبعاد المسؤولية عن الأضرار العرضية أو التبعية ، لذلك قد لا ينطبق عليك التقييد أو الاستثناء أعلاه وقد يكون لديك أيضًا حقوق قانونية أخرى تختلف من ولاية قضائية إلى أخرى.
<br><br><b>
13. التعويض</b><br><br>

باستخدام الخدمة ، فإنك توافق على تعويض كيانات الشركة والدفاع عنها وحمايتها من الضرر وضد أي وجميع المطالبات والطلبات والإجراءات والتكاليف والمسؤوليات والخسائر والأضرار من أي نوع (بما في ذلك أتعاب المحاماة) الناشئة عن أو المتعلقة استخدامك للخدمات ، أو انتهاكك لأي قوانين أو لوائح سارية ، أو خرقك لأي من شروط الخدمة هذه ، أو أي إجراء تتخذه الشركة كجزء من تحقيقها في انتهاك مشتبه به لشروط الخدمة هذه ، أو نتيجة لاستنتاجها أو قرارها بانتهاك شروط الخدمة. هذه الخدمة. هذا يعني أنه لا يمكنك مقاضاة أو استرداد أي أضرار من الشركة أو أي من كيانات الشركة نتيجة لقرارها بإزالة أو رفض المعالجة أو تقديم أي معلومات أو محتوى أو تحذيرك أو تعليق أو إنهاء وصولك إلى الخدمة ، أو اتخاذ أي إجراء آخر أثناء التحقيق في أي انتهاك مشتبه به أو نتيجة لاستنتاج الشركة بحدوث انتهاك لشروط الخدمة هذه. تنطبق شروط التنازل والتعويض على جميع الانتهاكات الموضحة في شروط الخدمة هذه أو الناتجة عن أو الناتجة عن استخدامك و / أو استخدامك للخدمة.
<br><br><b>
14. انتهاكات شروط الخدمة</b><br><br>

أ. يجوز للشركة الكشف عن أي معلومات لدينا عنك (بما في ذلك هويتك) إذا قررنا أن هذا الكشف ضروري فيما يتعلق بأي تحقيق أو شكوى تتعلق باستخدامك للخدمات أو لتحديد أو الاتصال أو رفع دعوى ضد أي شخص قد يتسبب في إصابة أو يتدخل (سواء عن قصد أو عن غير قصد) في حقوق أو ممتلكات الشركة أو حقوق أو ممتلكات الزوار أو مستخدمي الخدمة ، بما في ذلك عملاء الشركة. تحتفظ الشركة بالحق في جميع الأوقات في الكشف عن أي معلومات تراها الشركة ضرورية للامتثال لأي قانون أو لائحة أو إجراء قانوني أو طلب حكومي معمول به. يجوز للشركة أيضًا الكشف عن معلوماتك عندما تقرر الشركة أن القانون المعمول به يتطلب أو يسمح بهذا الكشف ، بما في ذلك تبادل المعلومات مع الشركات والمؤسسات الأخرى لأغراض الحماية من الاحتيال.
<br><br>
ب. أنت تقر وتوافق على أنه يجوز للشركة الاحتفاظ بأي مراسلات أو اتصالات من جانبك مع الشركة من خلال الخدمة ، ويجوز لها أيضًا الكشف عن هذه البيانات إذا لزم ذلك بموجب القانون أو قررت الشركة أن هذا الحفظ أو الكشف ضروري من أجل ( 1) الامتثال للإجراءات القانونية الواجبة ، (2) فرض شروط الخدمة هذه ، (3) الرد على الادعاءات بأن أيًا من هذه البيانات تنتهك حقوق الآخرين ، أو (4) حماية الحقوق أو الممتلكات. أو السلامة الشخصية للشركة أو موظفيها أو مستخدميها أو زوار الخدمة والجمهور.
<br><br>
ج. أنت توافق على أنه يجوز للشركة ، وفقًا لتقديرها المطلق ودون إشعار مسبق ، إنهاء وصولك إلى الخدمة و / أو منع وصولك المستقبلي إلى الخدمة إذا قررنا أنك انتهكت شروط الخدمة هذه أو اتفاقيات أو إرشادات أخرى قد أن تكون مرتبطة باستخدامك للخدمة. أنت توافق أيضًا على أن أي انتهاك من جانبك لشروط الخدمة هذه سيشكل ممارسة غير قانونية وغير عادلة للأعمال ، وسيؤدي إلى ضرر لا يمكن إصلاحه للشركة ، حيث تكون الأضرار المالية غير كافية ، وتوافق على أن تتلقى الشركة أي إجراءات قضائية أو قضائية. مجرد الإغاثة التي تراها الشركة ضرورية أو مناسبة في مثل هذه الظروف. هذه العلاجات هي بالإضافة إلى أي تعويضات أخرى قد تكون للشركة بموجب القانون أو في حقوق الملكية.
<br><br>
د. أنت توافق على أنه يجوز للشركة ، وفقًا لتقديرها المطلق ودون إشعار مسبق ، إنهاء وصولك إلى الخدمة ، بما في ذلك لأسباب (على سبيل المثال لا الحصر) (1) المطالبة بالقيام بذلك من قبل سلطات إنفاذ القانون أو الوكالات الحكومية الأخرى ، (2) ) طلب ذلك (عمليات حذف الحساب التي بدأها المستخدم) ، (3) انقطاع الخدمة أو تغييرها المادي ، أو (4) مشكلات أو مسائل فنية غير متوقعة.
<br><br>
ه. إذا اتخذت الشركة أي إجراء قانوني ضدك نتيجة لانتهاك شروط الخدمة هذه ، يحق للشركة الحصول على تعويض منك ، وتوافق على دفع جميع أتعاب المحاماة المعقولة وتكاليف هذا الإجراء ، بالإضافة إلى أي التعويضات الأخرى الممنوحة للشركة. أنت توافق أيضًا على أن الشركة لن تكون مسؤولة تجاهك أو تجاه أي طرف ثالث عن إنهاء وصولك إلى الخدمة نتيجة لأي انتهاك لشروط الخدمة هذه.
<br><br><b>
15. البطلان في حالة المنع</b><br><br>

على الرغم من أن الخدمة يمكن الوصول إليها في جميع أنحاء العالم ، إلا أن جميع الميزات أو المنتجات أو الخدمات التي تمت مناقشتها أو الإشارة إليها أو عرضها أو عرضها متاحة لجميع الأشخاص أو في جميع المواقع الجغرافية أو الملائمة أو المتاحة للاستخدام خارج مواقع جغرافية معينة. تحتفظ الشركة بالحق ، وفقًا لتقديرها المطلق ، في الحد من توفير وكمية أي ميزة أو منتج أو خدمة لأي شخص أو منطقة جغرافية. يعتبر أي عرض لأي ميزة أو منتج أو خدمة معروضة على الخدمات باطلاً حيثما كان محظورًا. إذا اخترت الوصول إلى الخدمات من خارج الموقع الجغرافي المعمول به ، فإنك تفعل ذلك بمبادرتك الخاصة ، وأنت وحدك المسؤول عن الامتثال للقوانين المحلية المعمول بها.
<br><br>
تدير الشركة الخدمة من مكاتبها في الولايات المتحدة وأوروبا. أنت توافق على الامتثال لجميع القوانين والقوانين واللوائح المحلية والتابعة للولاية والفيدرالية والوطنية التي تنطبق على استخدامك للخدمة. لا يمتلك أي موظف أو وكيل للشركة سلطة تغيير شروط الخدمة هذه.<br><br>
<b>
16. التنازل</b><br><br>

لا يشكل فشل الشركة في ممارسة أو إنفاذ أي حق أو شرط من شروط الخدمة هذه تنازلاً عن هذا الحق أو الحكم. لن يسري أي تنازل عن أي شرط من شروط الخدمة هذه إلا إذا تم ذلك صراحةً وكتابيًا وموقعًا من الشركة.
<br><br><b>
17. علاقة الطرفين
</b><br><br>
لا تنشئ شروط الخدمة هذه أي وكالة أو شراكة أو مشروع مشترك أو علاقة بين الموظف وصاحب العمل أو صاحب الامتياز الذي تم منحه صاحب الامتياز. شروط الخدمة هذه بينك وبين الشركة فقط وليست لصالح أي طرف ثالث.
<br><br><b>
18. القانون الواجب التطبيق والاختصاص القضائي والتحكيم
</b><br><br>
تخضع شروط الخدمة هذه لقوانين ولاية كاليفورنيا ، الولايات المتحدة الأمريكية ، بغض النظر عن تعارض أحكام القوانين. أنت وحدك المسؤول عن الامتثال لجميع القوانين المحلية المعمول بها داخل وخارج الولايات المتحدة ، بما في ذلك القوانين التي تتطلب منك عدم استخدام الخدمات. سيتم البت في أي مطالبة تنشأ عن أو تتعلق بشروط الخدمة هذه عن طريق التحكيم (ويوافق الطرفان بموجب هذا على الاختصاص الشخصي) في مقاطعة لوس أنجلوس ، كاليفورنيا بموجب إجراء تسوية المنازعات التجارية لجمعية التحكيم الأمريكية وبموجب ، في حالة وجود حكم الانتصاف القضائي أو المؤقت ، قواعد تدابير الحماية في حالات الطوارئ. يتم إصدار الحكم من قبل محكم واحد يكون حكمه نهائيًا وملزمًا ويمكن تنفيذه في أي محكمة ذات اختصاص قضائي. يحق للمحكوم عليه أتعاب وتكاليف المحاماة المعقولة. سيتم الحفاظ على سرية التحكيم باستثناء ما يقتضيه القانون. يجب تقديم أي مطالبات ناشئة عن أو تتعلق بشروط الخدمة هذه بصفته الفردية للطرف المنظم وليس كمدعي أو كعضو في الفصل في أي دعوى جماعية أو إجراءات أخرى مماثلة.
<br><br><b>
19. أحكام متنوعة</b><br><br>

لا يجوز لك استخدام أو تصدير أو إعادة تصدير أي محتوى أو أي نسخة أو تعديل لهذا المحتوى ، أو أي منتج أو خدمة مقدمة من خلال الخدمات ، بما يتعارض مع أي قوانين أو لوائح معمول بها.<br><br>

إذا تم الاحتفاظ بأي شرط من شروط الخدمة هذه من قبل محكمة أو سلطة قضائية مختصة أخرى غير صالحة أو غير قابلة للتنفيذ ، فيجب تقييد هذه الأحكام أو إزالتها إلى الحد الأدنى المطلوب واستبدالها بحكم صالح يعكس على أفضل وجه الغرض من هذه الشروط الخدمة ، بحيث تظل شروط الخدمة هذه سارية المفعول والتأثير الكامل. تشكل شروط الخدمة هذه مجمل الاتفاقية بينك وبين الشركة فيما يتعلق باستخدامك للخدمات ، ويجب إلغاء أي اتفاقيات أو تفاهمات مكتوبة أو شفهية أخرى أو تفاهمات مسبقة مبرمة بينك وبين الشركة فيما يتعلق بهذا الاستخدام و تغير. لن تقبل الشركة أي عروض تتعارض مع شروط الخدمة هذه ، وجميع هذه العروض مرفوضة رفضًا قاطعًا. لا يجوز تفسير فشل الشركة في الإصرار على أو فرض الأداء الصارم لشروط الخدمة هذه على أنه تنازل من قبل الشركة عن أي حكم أو حق لفرض شروط الخدمة هذه ، ولا يجوز تفسير أي سلوك بينك وبين الشركة أو الأطراف الأخرى تعتبر لتعديل أي شرط من شروط الخدمة هذه. لا يجوز تفسير شروط الخدمة هذه أو تفسيرها على أنها تمنح أي حقوق أو تعويضات لأي طرف ثالث.<br><br>

